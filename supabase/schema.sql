create or replace function public.spend_game_balance(p_amount numeric)
returns numeric
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_amount numeric(14, 2);
  v_balance numeric(14, 2);
begin
  if v_user_id is null then raise exception 'Sign in required'; end if;
  if p_amount is null or p_amount <= 0 or p_amount > 100000000 then
    raise exception 'Invalid game spend amount';
  end if;
  v_amount := round(p_amount, 2);

  update public.wallets w
     set balance = w.balance - v_amount,
         updated_at = now()
   where w.user_id = v_user_id and w.balance >= v_amount
   returning w.balance into v_balance;
  if v_balance is null then return null; end if;

  insert into public.wallet_transactions (user_id, actor_user_id, amount, reason)
  values (v_user_id, v_user_id, -v_amount, 'game_purchase');
  return v_balance;
end;
$$;

