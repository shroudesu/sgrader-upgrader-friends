create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  player_id bigint generated by default as identity unique not null,
  username text not null,
  role text not null default 'player' check (role in ('player', 'admin')),
  promo_code text check (promo_code is null or promo_code = 'SGRADER'),
  created_at timestamptz not null default now()
);

create unique index if not exists profiles_username_lower_unique
  on public.profiles (lower(username));

create table if not exists public.wallets (
  user_id uuid primary key references public.profiles(user_id) on delete cascade,
  balance numeric(14, 2) not null default 0 check (balance >= 0),
  updated_at timestamptz not null default now()
);

create table if not exists public.game_states (
  user_id uuid primary key references public.profiles(user_id) on delete cascade,
  state jsonb not null default '{"inventory":[],"betId":null,"targetName":null,"bestDrop":null}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.wallet_transactions (
  id bigint generated always as identity primary key,
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  actor_user_id uuid references public.profiles(user_id) on delete set null,
  amount numeric(14, 2) not null,
  bonus numeric(14, 2) not null default 0,
  reason text not null check (reason in ('admin_grant', 'admin_debit', 'game_sale', 'game_purchase')),
  created_at timestamptz not null default now()
);

alter table public.wallet_transactions
  drop constraint if exists wallet_transactions_reason_check;
alter table public.wallet_transactions
  add constraint wallet_transactions_reason_check
  check (reason in ('admin_grant', 'admin_debit', 'game_sale', 'game_purchase'));

create or replace function public.is_current_user_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles p
    where p.user_id = (select auth.uid()) and p.role = 'admin'
  );
$$;

revoke all on function public.is_current_user_admin() from public, anon;
grant execute on function public.is_current_user_admin() to authenticated;

create or replace function public.handle_new_game_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_username text;
begin
  v_username := trim(coalesce(new.raw_user_meta_data ->> 'username', ''));
  if length(v_username) < 3 or length(v_username) > 16
     or v_username !~ '^[A-Za-z0-9_А-Яа-яЁё]+$' then
    raise exception 'Invalid game username';
  end if;

  insert into public.profiles (user_id, username)
  values (new.id, v_username);
  insert into public.wallets (user_id, balance) values (new.id, 0);
  insert into public.game_states (user_id) values (new.id);
  return new;
end;
$$;

revoke all on function public.handle_new_game_user() from public, anon, authenticated;

drop trigger if exists on_auth_user_created_game_profile on auth.users;
create trigger on_auth_user_created_game_profile
  after insert on auth.users
  for each row execute function public.handle_new_game_user();

create or replace function public.apply_registration_promo(p_code text)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_existing_code text;
begin
  if v_user_id is null then raise exception 'Sign in required'; end if;
  if upper(trim(coalesce(p_code, ''))) <> 'SGRADER' then
    raise exception 'Invalid promo code';
  end if;

  update public.profiles
     set promo_code = 'SGRADER'
   where user_id = v_user_id and promo_code is null;
  if found then return true; end if;

  select promo_code into v_existing_code
    from public.profiles where user_id = v_user_id;
  if v_existing_code = 'SGRADER' then
    raise exception 'Promo code already used';
  end if;
  raise exception 'Profile not found';
end;
$$;

revoke all on function public.apply_registration_promo(text) from public, anon;
grant execute on function public.apply_registration_promo(text) to authenticated;

create or replace function public.admin_list_players()
returns table (
  player_id bigint,
  username text,
  role text,
  promo_code text,
  balance numeric
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.uid() is null or not public.is_current_user_admin() then
    raise exception 'Administrator access required' using errcode = '42501';
  end if;

  return query
    select p.player_id, p.username, p.role, p.promo_code, w.balance
      from public.profiles p
      join public.wallets w on w.user_id = p.user_id
     order by p.player_id;
end;
$$;

revoke all on function public.admin_list_players() from public, anon;
grant execute on function public.admin_list_players() to authenticated;

create or replace function public.admin_grant_demo_credits(
  p_player_id bigint,
  p_amount numeric
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_target uuid;
  v_username text;
  v_promo text;
  v_amount numeric(14, 2);
  v_bonus numeric(14, 2) := 0;
  v_balance numeric(14, 2);
begin
  if auth.uid() is null or not public.is_current_user_admin() then
    raise exception 'Administrator access required' using errcode = '42501';
  end if;
  if p_amount is null or p_amount <= 0 or p_amount > 100000000 then
    raise exception 'Amount must be between 0.01 and 100000000';
  end if;
  v_amount := round(p_amount, 2);

  select p.user_id, p.username, p.promo_code
    into v_target, v_username, v_promo
    from public.profiles p
   where p.player_id = p_player_id
   for update;
  if v_target is null then raise exception 'Player not found'; end if;

  if v_promo = 'SGRADER' then v_bonus := round(v_amount * 0.10, 2); end if;

  update public.wallets w
     set balance = w.balance + v_amount + v_bonus,
         updated_at = now()
   where w.user_id = v_target
   returning w.balance into v_balance;

  insert into public.wallet_transactions (user_id, actor_user_id, amount, bonus, reason)
  values (v_target, auth.uid(), v_amount, v_bonus, 'admin_grant');

  return jsonb_build_object(
    'player_id', p_player_id,
    'username', v_username,
    'amount', v_amount,
    'bonus', v_bonus,
    'balance', v_balance
  );
end;
$$;

revoke all on function public.admin_grant_demo_credits(bigint, numeric) from public, anon;
grant execute on function public.admin_grant_demo_credits(bigint, numeric) to authenticated;

create or replace function public.admin_debit_demo_credits(
  p_player_id bigint,
  p_amount numeric
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_target uuid;
  v_username text;
  v_amount numeric(14, 2);
  v_balance numeric(14, 2);
begin
  if auth.uid() is null or not public.is_current_user_admin() then
    raise exception 'Administrator access required' using errcode = '42501';
  end if;
  if p_amount is null or p_amount <= 0 or p_amount > 100000000 then
    raise exception 'Amount must be between 0.01 and 100000000';
  end if;
  v_amount := round(p_amount, 2);
  if v_amount <= 0 then raise exception 'Amount must be at least 0.01'; end if;

  select p.user_id, p.username
    into v_target, v_username
    from public.profiles p
   where p.player_id = p_player_id
   for update;
  if v_target is null then raise exception 'Player not found'; end if;

  select w.balance into v_balance
    from public.wallets w
   where w.user_id = v_target
   for update;
  if v_balance is null then raise exception 'Player wallet not found'; end if;
  if v_balance < v_amount then
    raise exception 'Insufficient balance' using errcode = '22023';
  end if;

  update public.wallets w
     set balance = w.balance - v_amount,
         updated_at = now()
   where w.user_id = v_target
   returning w.balance into v_balance;

  insert into public.wallet_transactions (user_id, actor_user_id, amount, bonus, reason)
  values (v_target, auth.uid(), -v_amount, 0, 'admin_debit');

  return jsonb_build_object(
    'player_id', p_player_id,
    'username', v_username,
    'amount', v_amount,
    'balance', v_balance
  );
end;
$$;

revoke all on function public.admin_debit_demo_credits(bigint, numeric) from public, anon;
grant execute on function public.admin_debit_demo_credits(bigint, numeric) to authenticated;

